// scripts/ios-colors.mjs — the SuperCOOKED colour tokens (src/ui/tokens.ts) as Swift,
// for the iPhone widget extension's Live Activity views (docs/specs/ios.md §2: the
// lock-screen designs use SuperCOOKED's colours, pinned to the tokens by a test).
// scripts/gen-ios-colors.mjs writes the source to ios/App/BigCoachWidgets/BrandColors.swift;
// tests/native/iosBrandColors.test.ts fails while that file is out of date with the tokens.
import { fileURLToPath } from 'node:url';
import { COLOR_TOKENS } from '../src/ui/tokens';

export const IOS_COLORS_PATH = fileURLToPath(new URL('../ios/App/BigCoachWidgets/BrandColors.swift', import.meta.url));

/** A token value ("#ff6b1a" or "rgba(11, 18, 32, 0.98)") as sRGB components 0–1. */
export function rgbaOf(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
  }
  const fn = /^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(value);
  if (fn) return [Number(fn[1]), Number(fn[2]), Number(fn[3]), fn[4] === undefined ? 1 : Number(fn[4])];
  throw new Error(`gen-ios-colors: cannot read colour ${value}`);
}

const num = (n) => String(Math.round(n * 10000) / 10000);

/** The Swift source for a set of tokens: one `Color` per token, in the tokens' order. */
export function swiftBrandColors(tokens = COLOR_TOKENS) {
  const lines = Object.entries(tokens).map(([name, value]) => {
    const [r, g, b, a] = rgbaOf(value);
    return `    /// ${value}\n    static let ${name} = Color(.sRGB, red: ${num(r / 255)}, green: ${num(g / 255)}, blue: ${num(b / 255)}, opacity: ${num(a)})`;
  });
  return [
    '// GENERATED by scripts/gen-ios-colors.mjs from src/ui/tokens.ts. Do not edit by hand:',
    '// change the token, then run `npx vite-node scripts/gen-ios-colors.mjs` (build:ios does).',
    '// tests/native/iosBrandColors.test.ts fails while this file is out of date.',
    '',
    'import SwiftUI',
    '',
    '/// The SuperCOOKED colour tokens (src/ui/tokens.ts) for the widget extension.',
    'enum BrandColor {',
    lines.join('\n'),
    '}',
    '',
  ].join('\n');
}

