export const GLYPH_W = 3;
export const GLYPH_H = 5;

/** Pixel width of a string (1px tracking between glyphs). */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + 1) - 1;
}

/** Call `plot(x, y)` for every lit pixel of `text` with its top-left at (0,0). */
export function drawText(text: string, plot: (x: number, y: number) => void): void {
  let cx = 0;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' ']!;
    g.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') plot(cx + x, y);
    });
    cx += GLYPH_W + 1;
  }
}
