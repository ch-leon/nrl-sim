// src/utils/hash.ts — a fast, stable, non-cryptographic string hash (#360).
// Used for the save checksum: the same payload string always gives the same
// hash, on every device and build. Not for security; no crypto dependency.

/**
 * cyrb53 (public domain, bryc): a 53-bit hash of `text`, as 14 hex digits.
 * Hashes UTF-16 code units, so it is exact for any string localStorage holds.
 */
export function cyrb53(text: string, seed = 0): string {
  let h1 = 0xdeadbeef ^ seed;
  let h2 = 0x41c6ce57 ^ seed;
  for (let i = 0; i < text.length; i++) {
    const ch = text.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  const n = 4294967296 * (2097151 & h2) + (h1 >>> 0);
  return n.toString(16).padStart(14, '0');
}
